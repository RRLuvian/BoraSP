// ---------- rodízio de placas (São Paulo) ----------
function getRodizioInfo(lang){
  const map = {
    1: {digits:"1, 2", label:{pt:"Segunda",en:"Monday",es:"Lunes",ja:"月曜",de:"Montag",it:"Lunedì",zh:"周一"}},
    2: {digits:"3, 4", label:{pt:"Terça",en:"Tuesday",es:"Martes",ja:"火曜",de:"Dienstag",it:"Martedì",zh:"周二"}},
    3: {digits:"5, 6", label:{pt:"Quarta",en:"Wednesday",es:"Miércoles",ja:"水曜",de:"Mittwoch",it:"Mercoledì",zh:"周三"}},
    4: {digits:"7, 8", label:{pt:"Quinta",en:"Thursday",es:"Jueves",ja:"木曜",de:"Donnerstag",it:"Giovedì",zh:"周四"}},
    5: {digits:"9, 0", label:{pt:"Sexta",en:"Friday",es:"Viernes",ja:"金曜",de:"Freitag",it:"Venerdì",zh:"周五"}}
  };
  const day = new Date().getDay(); // 0=domingo ... 6=sábado
  const info = map[day];
  if(!info) return null; // fim de semana: sem rodízio
  return `${info.digits}`;
}

// ---------- clima ao vivo (Open-Meteo, sem chave de API) ----------
async function loadWeatherChip(){
  try{
    const res = await fetch("https://api.open-meteo.com/v1/forecast?latitude=-23.5505&longitude=-46.6333&current=temperature_2m,weather_code&timezone=America/Sao_Paulo");
    const data = await res.json();
    const temp = Math.round(data.current.temperature_2m);
    const code = data.current.weather_code;
    // agrupamento simples dos weather codes do Open-Meteo
    let icon = "☀️", suggestKey = "sunny";
    if([61,63,65,80,81,82,95,96,99].includes(code)){ icon = "🌧️"; suggestKey = "rain"; }
    else if([1,2,3,45,48].includes(code)){ icon = "☁️"; suggestKey = "cloudy"; }
    else if([71,73,75,77,85,86].includes(code)){ icon = "❄️"; suggestKey = "cloudy"; }
    window.__weather = {temp, icon, suggestKey};
    renderLocalChips(document.documentElement.lang || 'pt');
  }catch(err){
    console.warn("Clima indisponível", err);
  }
}

function renderLocalChips(lang){
  const d = dict[lang];
  const el = document.getElementById('localChips');
  const rodizio = getRodizioInfo(lang);
  const rodizioHtml = rodizio
    ? `<div class="local-chip warn">🚗 ${esc(d.rodizioHoje)}: <b>${esc(rodizio)}</b></div>`
    : `<div class="local-chip">🚗 ${esc(d.rodizioLivre)}</div>`;
  const w = window.__weather;
  const temp = w ? Math.round(Number(w.temp)) : null;
  const weatherHtml = (w && Number.isFinite(temp))
    ? `<div class="local-chip">${esc(w.icon)} <b>${esc(temp)}°C</b> — ${esc(d.weatherSuggest[w.suggestKey])}</div>`
    : '';
  el.innerHTML = rodizioHtml + weatherHtml;
}

