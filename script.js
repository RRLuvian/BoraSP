async function fetchLiveEvents(){
  try{
    const res = await fetch('/api/feed');
    if(!res.ok) return [];
    const data = await res.json();
    return Array.isArray(data.items) ? data.items : [];
  }catch(err){
    console.warn('Feed ao vivo indisponível', err);
    return [];
  }
}

// normaliza texto pra comparação (minúsculas, sem acento, sem pontuação)
function normalizeTitle(s){
  return (s || "").toLowerCase()
    .normalize('NFD').replace(/[\u0300-\u036f]/g, '')
    .replace(/[^\w\s]/g, ' ').replace(/\s+/g, ' ').trim();
}

// checa se um evento do RSS é provavelmente o mesmo que já está curado (afiliado)
// melhor esforço por palavras-chave — não é uma correspondência perfeita
function isDuplicateOfCurated(rssTitle){
  const rssNorm = normalizeTitle(rssTitle);
  return curatedEvents.some(ce => {
    const words = normalizeTitle(ce.title).split(' ').filter(w => w.length > 3).slice(0, 3);
    return words.length > 0 && words.every(w => rssNorm.includes(w));
  });
}

async function loadLiveEvents(){
  const liveEvents = (await fetchLiveEvents())
    .filter(le => !isDuplicateOfCurated(le.title)); // evita duplicar evento que já tem link de afiliado

  // sempre mantém os eventos curados (afiliado) na lista — só acrescenta o RSS por cima
  events.length = 0;
  events.push(...curatedEvents, ...liveEvents);
  renderFeatured('railEventos', events);
  renderFeatured('railIntl', internacional);
  applyLang(document.documentElement.lang || 'pt');
}

