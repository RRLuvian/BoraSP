// ---------- segurança: escapar texto antes de inserir no HTML ----------
// Qualquer texto vindo de fora (RSS, JSON) passa por aqui antes de virar innerHTML.
function esc(str){
  return String(str ?? '').replace(/[&<>"']/g, c => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'
  }[c]));
}

// Só aceita http/https como URL válida (bloqueia javascript:, data:, etc.)
function slugify(str){
  return String(str || '')
    .toLowerCase()
    .normalize('NFD').replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '')
    .slice(0, 60);
}

// Monta a URL de clique rastreado (/api/click) para cards afiliados.
// Cards não-afiliados continuam abrindo o modal normalmente (sem passar por aqui).
function buildClickUrl(it, section){
  const link = safeUrl(it.link);
  if(!link) return '#';
  const params = new URLSearchParams({
    to: link,
    id: slugify(it.title),
    sec: section,
    src: it.source || ''
  });
  return '/api/click?' + params.toString();
}

function safeUrl(url){
  if(!url) return '';
  try{
    const u = new URL(url, window.location.href);
    return (u.protocol === 'http:' || u.protocol === 'https:') ? u.href : '';
  }catch(_){ return ''; }
}

